"""Generate Tree-sitter syntax-island grammars from the expansion grammar.

Tree-sitter checks structure; semantic constraints such as matching tag names
remain compiler/front-end diagnostics. Host-code nodes are language injections.
"""
from pathlib import Path
import json
import re
import shutil

from engine import Grammar

HERE = Path(__file__).resolve().parent


def generate(path):
    grammar = Grammar(path)
    name = "cinch_" + grammar.data["name"].replace("-", "_")
    directory = HERE / "editor" / ("tree-sitter-" + name.replace("_", "-"))
    (directory / "src").mkdir(parents=True, exist_ok=True)
    (directory / "queries").mkdir(exist_ok=True)
    captures, serial, capture_ids = {}, 0, {}
    def convert(pattern):
        nonlocal serial
        if isinstance(pattern, str): return json.dumps(pattern)
        if isinstance(pattern, list): return "seq(" + ", ".join(convert(p) for p in pattern) + ")"
        if "capture" in pattern:
            if isinstance(pattern["of"], dict) and "many" in pattern["of"]:
                return convert(pattern["of"])
            identity = (pattern["capture"], json.dumps(pattern["of"], sort_keys=True))
            if identity in capture_ids:
                return f'field({json.dumps(pattern["capture"])}, $.{capture_ids[identity]})'
            serial += 1
            key = "capture_" + pattern["capture"] + "_" + str(serial)
            capture_ids[identity] = key
            captures[key] = (pattern["capture"], convert(pattern["of"]))
            return f'field({json.dumps(pattern["capture"])}, $.{key})'
        if "ref" in pattern: return "$." + pattern["ref"].replace("-", "_")
        if "regex" in pattern: return "/" + pattern["regex"].replace("/", "\\/") + "/"
        if "quote" in pattern: return convert(pattern["quote"])
        if "host" in pattern: return "$.host_expression"
        if "choice" in pattern: return "choice(" + ", ".join(convert(p) for p in pattern["choice"]) + ")"
        if "many" in pattern:
            repeat = "repeat1" if pattern.get("min", 0) else "repeat"
            return repeat + "(" + convert(pattern["many"]) + ")"
        raise ValueError(pattern)
    rules = {key.replace("-", "_"): convert(value["pattern"]) for key, value in grammar.rules.items()}
    entries = [f'    source_file: $ => repeat1(seq("{{", $.{grammar.entry})), ',
               '    host_expression: $ => seq("{", optional($.host_code), "}"),']
    entries.extend(f"    {key}: $ => {value}," for key, value in rules.items())
    entries.extend(f"    {key}: $ => {value}," for key, (_, value) in captures.items())
    source = "// Generated by editor_generate.py; edit the syntax library.\n"
    source += f'module.exports = grammar({{\n  name: "{name}",\n  externals: $ => [$.host_code],\n'
    source += '  extras: $ => [/\\s/],\n  rules: {\n' + "\n".join(entries) + '\n  }\n});\n'
    (directory / "grammar.js").write_text(source)
    (directory / "src/scanner.c").write_text(SCANNER.replace("LANGUAGE", name))
    (directory / "tree-sitter.json").write_text(json.dumps({
        "grammars": [{"name": name, "camelcase": "".join(x.capitalize() for x in name.split("_")),
                      "scope": "source." + name, "path": ".", "file-types": [name],
                      "injection-regex": "^(?:" + name + "|" + re.escape(grammar.data["name"]) + ")$", "highlights": "queries/highlights.scm",
                      "injections": "queries/injections.scm"}],
        "metadata": {"version": "0.1.0", "license": "UNLICENSED", "description": "Experimental Cinch syntax library", "authors": [{"name": "Cinch"}], "links": {"repository": "https://github.com/mercurytechnologies/designing-a-safe-language"}},
        "bindings": {}}, indent=2) + "\n")
    highlights = []
    for key, (capture, _) in captures.items():
        category = grammar.data.get("editor", {}).get("highlights", {}).get(capture)
        if category: highlights.append(f"({key}) @{category}")
    # Text is a lexical node, independent of successful elaboration.
    if "text" in rules: highlights.append("(text) @string")
    (directory / "queries/highlights.scm").write_text("\n".join(highlights) + "\n")
    (directory / "queries/injections.scm").write_text('((host_code) @injection.content\n (#set! injection.language "cinch_expr"))\n')
    return directory


def generate_expression():
    directory = HERE / 'editor/tree-sitter-cinch-expr'
    (directory / 'src').mkdir(parents=True, exist_ok=True)
    base = HERE.parents[1] / 'tooling/tree-sitter-cinch'
    relative = __import__('os').path.relpath(base / 'grammar.js', directory)
    (directory / 'grammar.js').write_text(f'const base = require({json.dumps(relative)});\nmodule.exports = grammar(base, {{name: "cinch_expr", rules: {{ source_file: $ => $._term }} }});\n')
    descriptors = [Grammar(p) for p in sorted((HERE / 'syntax').glob('*.syntax.json'))]
    raw_aliases = [g.data['name'] for g in descriptors if g.data.get('editor', {}).get('reader') == 'text-tag-code']
    scanner = parent_scanner(base, 'cinch_expr', raw_aliases)
    (directory / 'src/scanner.c').write_text(scanner)
    metadata = json.loads((base / 'tree-sitter.json').read_text())
    metadata['grammars'][0].update(name='cinch_expr', camelcase='CinchExpr', scope='source.cinch_expr', **{'file-types': ['cinch_expr']})
    metadata['grammars'][0].update({'injection-regex': '^cinch_expr$', 'highlights': 'queries/highlights.scm', 'injections': 'queries/injections.scm'})
    (directory / 'tree-sitter.json').write_text(json.dumps(metadata, indent=2) + '\n')
    (directory / 'queries').mkdir(exist_ok=True)
    highlights = (HERE.parents[1] / 'tooling/editors/zed/languages/cinch/highlights.scm').read_text()
    (directory / 'queries/highlights.scm').write_text(highlights.replace('(token_tree) @string', ''))
    (directory / 'queries/injections.scm').write_text(injection_query({g.data['name']: 'cinch_' + g.data['name'].replace('-', '_') for g in descriptors}))
    return directory


def injection_query(aliases):
    return ''.join(
        '((macro_invocation (variable (identifier) @_syntax_name)\n'
        '  (token_tree) @injection.content)\n'
        f' (#eq? @_syntax_name {json.dumps(alias)})\n'
        f' (#set! injection.language {json.dumps(language)})\n'
        ' (#set! injection.combined))\n'
        for alias, language in sorted(aliases.items()))


def parent_scanner(base, name, raw_aliases):
    """Specialize the parent's *boundary reader*, not the expansion rules.

    A library's editor reader declares text/tag/code lexical modes. Its actual
    language grammar is still generated independently from the shared rules.
    """
    scanner = (base / 'src/scanner.c').read_text()
    scanner = scanner.replace('tree_sitter_cinch_external', f'tree_sitter_{name}_external')
    scanner = scanner.replace('  bool bang_pending;', '  bool bang_pending;\n  bool syntax_markup;')
    condition = ' || '.join(f'strcmp(s->last_word, {json.dumps(alias)}) == 0' for alias in raw_aliases) or 'false'
    needle = 'uint32_t tok_col) {\n  if (tc->kind == KIND_WORD)'
    replacement = f'uint32_t tok_col) {{\n  bool syntax_markup = tc->symbol == BANG && ({condition});\n  if (tc->kind == KIND_WORD)'
    if needle not in scanner: raise ValueError('parent scanner note hook drifted')
    scanner = scanner.replace(needle, replacement)
    scanner = scanner.replace('    s->bang_pending = true;', '    s->bang_pending = true;\n    s->syntax_markup = syntax_markup;')
    marker = '/* The balanced raw capture of a macro token tree'
    if marker not in scanner: raise ValueError('parent scanner boundary hook drifted')
    scanner = scanner.replace(marker, PARENT_READER + '\n' + marker)
    needle = "if (!scan_token_tree(s, lexer, 1, '}')) return false;"
    if needle not in scanner: raise ValueError('parent scanner token tree hook drifted')
    scanner = scanner.replace(needle, "if (s->syntax_markup) { if (!scan_markup_island(s, lexer)) return false; }\n      else if (!scan_token_tree(s, lexer, 1, '}')) return false;")
    return scanner


def generate_project(sources):
    from engine import Engine
    aliases, raw_aliases = {}, []
    for path in sources:
        engine = Engine(Path(path).read_text(), path)
        for imported in engine.imports:
            descriptor = Grammar(imported['path'])
            alias, language = imported['alias'], 'cinch_' + descriptor.data['name'].replace('-', '_')
            if alias in aliases and aliases[alias] != language:
                raise ValueError(f'project has conflicting editor syntax alias `{alias}`; per-document parser selection is required')
            aliases[alias] = language
            if descriptor.data.get('editor', {}).get('reader') == 'text-tag-code': raw_aliases.append(alias)
    directory = HERE / 'editor/tree-sitter-cinch-project'
    (directory / 'src').mkdir(parents=True, exist_ok=True)
    (directory / 'queries').mkdir(exist_ok=True)
    base = HERE.parents[1] / 'tooling/tree-sitter-cinch'
    relative = __import__('os').path.relpath(base / 'grammar.js', directory)
    (directory / 'grammar.js').write_text(f'''// Generated project composition; the core grammar is inherited.
const base = require({json.dumps(relative)});
module.exports = grammar(base, {{
  name: "cinch_project",
  rules: {{
    declaration: ($, original) => choice($.syntax_import, $.macro_invocation, original),
    syntax_import: $ => seq($.kw_import, field("qualifier", $.identifier), $.string_literal, $.kw_as, field("alias", $.identifier)),
  }}
}});
''')
    (directory / 'src/scanner.c').write_text(parent_scanner(base, 'cinch_project', sorted(set(raw_aliases))))
    metadata = json.loads((base / 'tree-sitter.json').read_text())
    metadata['grammars'][0].update(name='cinch_project', camelcase='CinchProject', scope='source.cinch_project', **{'file-types': ['cinch']})
    metadata['grammars'][0].update({'highlights': 'queries/highlights.scm', 'injections': 'queries/injections.scm'})
    (directory / 'tree-sitter.json').write_text(json.dumps(metadata, indent=2) + '\n')
    highlights = (HERE.parents[1] / 'tooling/editors/zed/languages/cinch/highlights.scm').read_text()
    (directory / 'queries/highlights.scm').write_text(highlights.replace('(token_tree) @string', '') + '\n(syntax_import qualifier: (identifier) @keyword)\n')
    (directory / 'queries/injections.scm').write_text(injection_query(aliases))
    for language in sorted(set(aliases.values())):
        metadata_path = HERE / 'editor' / ('tree-sitter-' + language.replace('_', '-')) / 'tree-sitter.json'
        data = json.loads(metadata_path.read_text())
        names = [language] + [alias for alias, target in aliases.items() if target == language]
        data['grammars'][0]['injection-regex'] = '^(?:' + '|'.join(re.escape(n) for n in sorted(names)) + ')$'
        metadata_path.write_text(json.dumps(data, indent=2) + '\n')
    return directory


PARENT_READER = r'''
/* Library-declared text/tag/code modes for finding an island's boundary.
   Strings and comments have Cinch meaning only inside a host-code hole. */
static bool scan_host_hole(Scanner *s, TSLexer *l) {
  unsigned depth = 1, comment = 0;
  bool string = false, line_comment = false;
  while (!at_eof(l)) {
    char c = peekc(l); take(s, l, false);
    if (line_comment) { if (c == '\n') line_comment = false; continue; }
    if (string) {
      if (c == '\\' && !at_eof(l)) take(s, l, false);
      else if (c == '"') string = false;
      continue;
    }
    if (comment) {
      if (c == '{' && peekc(l) == '-') { take(s,l,false); comment++; }
      else if (c == '-' && peekc(l) == '}') { take(s,l,false); comment--; }
      continue;
    }
    if (c == '"') string = true;
    else if (c == '-' && peekc(l) == '-') { take(s,l,false); line_comment = true; }
    else if (c == '{' && peekc(l) == '-') { take(s,l,false); comment = 1; }
    else if (c == '{') depth++;
    else if (c == '}') { if (--depth == 0) return true; }
    else if (c == '\'') {
      if (peekc(l) == '\\') {
        take(s,l,false);
        if (peekc(l) == 'u') {
          take(s,l,false);
          if (peekc(l) == '{') {
            take(s,l,false);
            while (!at_eof(l) && peekc(l) != '}') take(s,l,false);
            if (!at_eof(l)) take(s,l,false);
          }
        } else if (!at_eof(l)) take(s,l,false);
        if (peekc(l) == '\'') take(s,l,false);
      } else if (!at_eof(l)) {
        take(s,l,false);
        if (peekc(l) == '\'') take(s,l,false);
      }
    }
  }
  return false;
}
static bool scan_markup_island(Scanner *s, TSLexer *l) {
  bool tag = false, quoted = false;
  while (!at_eof(l)) {
    char c = peekc(l); take(s,l,false);
    if (quoted) { if (c == '"') quoted = false; continue; }
    if (tag && c == '"') { quoted = true; continue; }
    if (c == '{') { if (!scan_host_hole(s,l)) return false; continue; }
    if (c == '}') { mark(s,l); return true; }
    if (c == '<') tag = true;
    else if (c == '>') tag = false;
  }
  return false;
}
'''


SCANNER = r'''// Generated host-code boundary scanner. No domain grammar is embedded here.
#include "tree_sitter/parser.h"
#include <stdlib.h>
void *tree_sitter_LANGUAGE_external_scanner_create(void) { return NULL; }
void tree_sitter_LANGUAGE_external_scanner_destroy(void *p) { (void)p; }
unsigned tree_sitter_LANGUAGE_external_scanner_serialize(void *p, char *b) { (void)p; (void)b; return 0; }
void tree_sitter_LANGUAGE_external_scanner_deserialize(void *p, const char *b, unsigned n) { (void)p; (void)b; (void)n; }
static void advance(TSLexer *l) { l->advance(l, false); }
bool tree_sitter_LANGUAGE_external_scanner_scan(void *p, TSLexer *l, const bool *valid) {
  (void)p;
  if (!valid[0] || l->lookahead == '}' || l->eof(l)) return false;
  unsigned braces = 0, comments = 0;
  bool string = false, line_comment = false;
  while (!l->eof(l)) {
    int32_t c = l->lookahead;
    if (line_comment) { advance(l); if (c == '\n') line_comment = false; continue; }
    if (string) {
      advance(l);
      if (c == '\\' && !l->eof(l)) advance(l);
      else if (c == '"') string = false;
      continue;
    }
    if (comments) {
      advance(l);
      if (c == '{' && l->lookahead == '-') { advance(l); comments++; }
      else if (c == '-' && l->lookahead == '}') { advance(l); comments--; }
      continue;
    }
    if (c == '}' && braces == 0) break;
    advance(l);
    if (c == '"') string = true;
    else if (c == '-' && l->lookahead == '-') { advance(l); line_comment = true; }
    else if (c == '{' && l->lookahead == '-') { advance(l); comments = 1; }
    else if (c == '{') braces++;
    else if (c == '}') braces--;
    else if (c == '\'') {
      // A single codepoint character has a closing tick. Tick identifiers
      // remain ordinary code. Escaped characters consume their closing tick.
      if (l->lookahead == '\\') {
        advance(l);
        if (l->lookahead == 'u') {
          advance(l);
          if (l->lookahead == '{') {
            advance(l);
            while (!l->eof(l) && l->lookahead != '}') advance(l);
            if (!l->eof(l)) advance(l);
          }
        } else if (!l->eof(l)) advance(l);
        if (l->lookahead == '\'') advance(l);
      } else if (!l->eof(l) && l->lookahead != '}') {
        advance(l);
        if (l->lookahead == '\'') advance(l);
      } else if (l->lookahead == '}') {
        // This may be the character '}', so inspect its following tick.
        l->mark_end(l);
        advance(l);
        if (l->lookahead == '\'') advance(l);
        else { l->result_symbol = 0; return true; }
      }
    }
    l->mark_end(l);
  }
  l->mark_end(l);
  l->result_symbol = 0;
  return true;
}
'''


