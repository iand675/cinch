#!/usr/bin/env python3
"""Generate exact immutable Unicode catalogs separately from the String-free numeric core."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tooling/data/unicode17-tables.json'
LAYOUT = ROOT / 'tooling/data/unicode17-layout.json'


def lookup(name: str, entries: dict[str, str]) -> str:
    """Render a shallow byte-lexicographic lookup with exact case-sensitive names."""
    items = sorted(entries.items())
    lines = [f'  -- | Resolve one exact immutable {name} name without normalizing punctuation or case.', f'  {name} :: String -> Option UnicodeRangeTable', f'  {name} name =']

    def tree(rows: list[tuple[str, str]], indent: int) -> None:
        """Keep comparison depth logarithmic without constructing a runtime dictionary."""
        pad = ' ' * indent
        if not rows:
            lines.append(pad + 'None')
            return
        middle = len(rows) // 2
        key, value = rows[middle]
        lines.append(pad + f'let order = string-compare name {json.dumps(key)} in')
        lines.append(pad + 'if lt-i64 order 0 then')
        tree(rows[:middle], indent + 2)
        lines.append(pad + f'else if eq-i64 order 0 then unicode-builtin-range-table {value}')
        lines.append(pad + 'else')
        tree(rows[middle + 1:], indent + 2)

    tree(items, 4)
    return '\n'.join(lines) + '\n'


def literal_keys(name: str, values: list[str]) -> list[str]:
    """Keep each literal-selection case shallow, including the larger script and alias catalogs."""
    pages = [values[start:start + 64] for start in range(0, len(values), 64)]
    out = [f'  -- | Select a shared immutable {name} literal through bounded shallow pages.', f'  {name}-key :: U32 -> String', f'  {name}-key index =']
    for page in range(len(pages)):
        prefix = 'if' if page == 0 else 'else if'
        out.extend([f'    {prefix} lt-u32 index {(page + 1) * 64} then', f'      let local = wrapping-sub-u32 index {page * 64} in {name}-keys-{chr(97 + page)} local'])
    out.append('    else ""')
    for index, page in enumerate(pages):
        out.extend(['', f'  -- | One complete shallow page of immutable {name} key literals.', f'  {name}-keys-{chr(97 + index)} :: U32 -> String', f'  {name}-keys-{chr(97 + index)} index = case index of'])
        out.extend(f'    {index} -> {json.dumps(value)}' for index, value in enumerate(page))
        out.append('    other -> ""')
    return out


def names(name: str, values: list[str]) -> str:
    """Expose complete key observations without a giant constant constructor list."""
    out = [f'  -- | Count the exact {name} catalog keys, including documented aliases.', f'  {name}-count :: Nat', f'  {name}-count = {len(values)}', '', f'  -- | Read one sorted immutable {name} key; invalid indices return None.', f'  {name}-name :: Nat -> Option String', f'  {name}-name index = if index < {len(values)} then Some ({name}-key (wrapping-i64-to-u32 (nat-to-i64 index))) else None']
    out.extend(literal_keys(name, values))
    out.extend(['', f'  -- | Collect the catalog keys in sorted order with bounded traversal stack.', f'  {name}-names-from :: Nat -> List String -> List String', f'  {name}-names-from count out = if count > 0 && count <= {len(values)} then', f'    let index = count - 1 in let key = {name}-key (wrapping-i64-to-u32 (nat-to-i64 index)) in', f'    {name}-names-from index (Cons key out)', '    else out', '', f'  -- | Observe every {name} key without exposing or copying range-table storage.', f'  {name}-names :: Unit -> List String', f'  {name}-names unit = {name}-names-from {len(values)} Nil'])
    return '\n'.join(out) + '\n'


def generated() -> str:
    """Generate all exact public catalogs, aliases and primary class-name observations."""
    data = json.loads(DATA.read_text())
    layout = json.loads(LAYOUT.read_text())
    ids = layout['table_ids']
    catalogs = {'unicode-category': data['catalogs']['Categories'], 'unicode-script': data['catalogs']['Scripts'], 'unicode-property': data['catalogs']['Properties'], 'unicode-fold-category': data['catalogs']['FoldCategory'], 'unicode-fold-script': data['catalogs']['FoldScript'], 'unicode-table': data['exported_aliases']}
    lines = ['-- | Exact immutable Unicode 17.0.0 named table catalogs and aliases.', '-- Generated by tooling/generate_unicode_names.py. Original data provenance', '-- and licensing are preserved beside tooling/data/unicode17-tables.json.', '-- This String-facing catalog stays outside the numeric classification core.', 'module Data.Unicode.Names where', '  import Data.Unicode.Range', '  import Data.Unicode.Tables', '  import Data.List', '  import Data.Machine', '  import Data.Nat', '  import Data.Option', '  import Data.String', '']
    for name in catalogs:
        lines.append('  export ' + ', '.join([name, name+'-count', name+'-name', name+'-names']))
    lines += ['  export unicode-category-canonical, unicode-category-alias-count, unicode-category-alias-at', '  export unicode-category-of-code, unicode-script-of-code', '']
    for name, entries in catalogs.items():
        lines.append(lookup(name, {key: str(ids[target]) for key, target in entries.items()}))
        lines.append(names(name, sorted(entries)))
    aliases = sorted(data['category_aliases'].items())
    lines += ['  -- | Resolve an exact standard category alias to its canonical abbreviated name.', '  unicode-category-canonical :: String -> Option String', '  unicode-category-canonical name =']
    for index, (key, value) in enumerate(aliases):
        lines.append('    ' + ('if' if index == 0 else 'else if') + f' name == {json.dumps(key)} then Some {json.dumps(value)}')
    lines.append('    else None')
    lines += ['', '  -- | Number of immutable category-alias observations.', '  unicode-category-alias-count :: Nat', f'  unicode-category-alias-count = {len(aliases)}', '', '  -- | Observe one sorted alias and its canonical category name; invalid indices return None.', '  unicode-category-alias-at :: Nat -> Option (String, String)', '  unicode-category-alias-at index =']
    for index, (key, value) in enumerate(aliases):
        lines.append('    ' + ('if' if index == 0 else 'else if') + f' index == {index} then Some ({json.dumps(key)}, {json.dumps(value)})')
    lines.append('    else None')
    for name, values, expression in [('category', layout['categories'], 'wrapping-u64-to-u32 (bit-and-u64 word 31)'), ('script', layout['scripts'], 'wrapping-u64-to-u32 (bit-and-u64 (wrapping-shr-u64 word 5) 255)')]:
        lines += ['', f'  -- | Observe the primary {name} of any numeric Unicode code point; invalid or unassigned scripts return None.', f'  unicode-{name}-of-code :: I32 -> Option String', f'  unicode-{name}-of-code cp = if ge-i32 cp 0 && le-i32 cp 1114111 then', '    let raw = wrapping-i32-to-u32 cp in let word = unicode-data-class raw in', f'    let index = {expression} in', f'    if lt-u32 index {len(values)} then Some (primary-{name}-key index) else None', '    else None']
        lines.extend(literal_keys('primary-' + name, values))
    return '\n'.join(lines) + '\n'


def main() -> None:
    """Write or verify the catalog module without changing numeric table data."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--module', type=Path, default=ROOT / 'compiler/prelude/Data/Unicode/Names.cinch')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    if args.check:
        if not args.module.exists() or args.module.read_text() != text:
            raise SystemExit('stale Unicode catalog source')
    else:
        args.module.parent.mkdir(parents=True, exist_ok=True)
        args.module.write_text(text)


if __name__ == '__main__':
    main()
