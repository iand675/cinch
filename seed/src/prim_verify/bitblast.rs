pub const LRAT_FORMAT_ID: &str = "lrat/v1";
pub const BITBLAST_VERSION_ID: &str = "cinch-bitblast@1";

/// Maximum CNF clauses generated by bit-blasting before yielding `Unknown`
/// (prevents huge 128-bit multipliers/dividers from blowing up SAT).
pub const DEFAULT_MAX_CLAUSES: usize = 250_000;
/// Maximum CDCL conflicts before returning `Unknown`.
pub const DEFAULT_MAX_CONFLICTS: usize = 50_000;

/// Canonical CNF formula derived deterministically from `!obligation.goal`.
#[derive(Clone, Debug)]
pub struct CnfFormula {
    pub num_vars: usize,
    /// Original clauses, 1-indexed in LRAT (`clauses[0]` has clause ID 1).
    pub clauses: Vec<Vec<i32>>,
    /// Mapping from parameter index to its CNF bit variables (LSB first).
    pub param_bits: Vec<(usize, SemTy, Vec<i32>)>,
}

/// Bit-blasting error (e.g. floating-point node or circuit size budget exceeded).
#[derive(Clone, Debug)]
pub enum BitBlastError {
    UnsupportedOp(String),
    BudgetExceeded(String),
}

struct Tseitin {
    next_var: i32,
    clauses: Vec<Vec<i32>>,
    max_clauses: usize,
    true_lit: i32,
}

impl Tseitin {
    fn new(max_clauses: usize) -> Self {
        // Variable 1 is fixed to TRUE by unit clause `[1]`.
        let mut t = Self {
            next_var: 2,
            clauses: Vec::new(),
            max_clauses,
            true_lit: 1,
        };
        t.clauses.push(vec![1]);
        t
    }

    fn fresh(&mut self) -> i32 {
        let v = self.next_var;
        self.next_var += 1;
        v
    }

    fn false_lit(&self) -> i32 {
        -self.true_lit
    }

    fn add_clause(&mut self, mut lits: Vec<i32>) -> Result<(), BitBlastError> {
        if self.clauses.len() >= self.max_clauses {
            return Err(BitBlastError::BudgetExceeded(format!(
                "bit-blast exceeded {} clauses",
                self.max_clauses
            )));
        }
        lits.sort_unstable();
        lits.dedup();
        // Drop tautologies (contains both x and -x).
        for &l in &lits {
            if lits.binary_search(&-l).is_ok() {
                return Ok(());
            }
        }
        self.clauses.push(lits);
        Ok(())
    }

    fn mk_and(&mut self, a: i32, b: i32) -> Result<i32, BitBlastError> {
        if a == self.false_lit() || b == self.false_lit() || a == -b {
            return Ok(self.false_lit());
        }
        if a == self.true_lit {
            return Ok(b);
        }
        if b == self.true_lit || a == b {
            return Ok(a);
        }
        let z = self.fresh();
        self.add_clause(vec![-z, a])?;
        self.add_clause(vec![-z, b])?;
        self.add_clause(vec![z, -a, -b])?;
        Ok(z)
    }

    fn mk_or(&mut self, a: i32, b: i32) -> Result<i32, BitBlastError> {
        if a == self.true_lit || b == self.true_lit || a == -b {
            return Ok(self.true_lit);
        }
        if a == self.false_lit() {
            return Ok(b);
        }
        if b == self.false_lit() || a == b {
            return Ok(a);
        }
        let z = self.fresh();
        self.add_clause(vec![-a, z])?;
        self.add_clause(vec![-b, z])?;
        self.add_clause(vec![-z, a, b])?;
        Ok(z)
    }

    fn mk_xor(&mut self, a: i32, b: i32) -> Result<i32, BitBlastError> {
        if a == self.false_lit() {
            return Ok(b);
        }
        if b == self.false_lit() {
            return Ok(a);
        }
        if a == self.true_lit {
            return Ok(-b);
        }
        if b == self.true_lit {
            return Ok(-a);
        }
        if a == b {
            return Ok(self.false_lit());
        }
        if a == -b {
            return Ok(self.true_lit);
        }
        let z = self.fresh();
        self.add_clause(vec![-z, -a, -b])?;
        self.add_clause(vec![-z, a, b])?;
        self.add_clause(vec![z, -a, b])?;
        self.add_clause(vec![z, a, -b])?;
        Ok(z)
    }

    fn mk_iff(&mut self, a: i32, b: i32) -> Result<i32, BitBlastError> {
        let x = self.mk_xor(a, b)?;
        Ok(-x)
    }

    fn mk_ite(&mut self, c: i32, t: i32, e: i32) -> Result<i32, BitBlastError> {
        if c == self.true_lit {
            return Ok(t);
        }
        if c == self.false_lit() {
            return Ok(e);
        }
        if t == e {
            return Ok(t);
        }
        let z = self.fresh();
        self.add_clause(vec![-c, -t, z])?;
        self.add_clause(vec![-c, t, -z])?;
        self.add_clause(vec![c, -e, z])?;
        self.add_clause(vec![c, e, -z])?;
        Ok(z)
    }

    fn mk_bv_const(&self, width: u16, bits: u128) -> Vec<i32> {
        (0..width)
            .map(|i| {
                if i < 128 && ((bits >> i) & 1) != 0 {
                    self.true_lit
                } else {
                    self.false_lit()
                }
            })
            .collect()
    }

    fn mk_bv_add(&mut self, a: &[i32], b: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let mut out = Vec::with_capacity(a.len());
        let mut carry = self.false_lit();
        for (&ai, &bi) in a.iter().zip(b.iter()) {
            let axorb = self.mk_xor(ai, bi)?;
            let sum = self.mk_xor(axorb, carry)?;
            let ab = self.mk_and(ai, bi)?;
            let cx = self.mk_and(carry, axorb)?;
            carry = self.mk_or(ab, cx)?;
            out.push(sum);
        }
        Ok(out)
    }

    fn mk_bv_sub(&mut self, a: &[i32], b: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        // a - b = a + (~b) + 1
        let mut out = Vec::with_capacity(a.len());
        let mut carry = self.true_lit;
        for (&ai, &bi) in a.iter().zip(b.iter()) {
            let nbi = -bi;
            let axorb = self.mk_xor(ai, nbi)?;
            let sum = self.mk_xor(axorb, carry)?;
            let ab = self.mk_and(ai, nbi)?;
            let cx = self.mk_and(carry, axorb)?;
            carry = self.mk_or(ab, cx)?;
            out.push(sum);
        }
        Ok(out)
    }

    fn mk_bv_eq(&mut self, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        let mut acc = self.true_lit;
        for (&ai, &bi) in a.iter().zip(b.iter()) {
            let eq = self.mk_iff(ai, bi)?;
            acc = self.mk_and(acc, eq)?;
        }
        Ok(acc)
    }

    fn mk_bv_ult(&mut self, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        // Scan from LSB to MSB: ult_i = (!a_i & b_i) | ((a_i == b_i) & ult_{i-1})
        let mut lt = self.false_lit();
        for (&ai, &bi) in a.iter().zip(b.iter()) {
            let strictly = self.mk_and(-ai, bi)?;
            let eq = self.mk_iff(ai, bi)?;
            let carry = self.mk_and(eq, lt)?;
            lt = self.mk_or(strictly, carry)?;
        }
        Ok(lt)
    }

    fn mk_bv_ule(&mut self, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        let gt = self.mk_bv_ult(b, a)?;
        Ok(-gt)
    }

    fn mk_bv_slt(&mut self, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        let n = a.len();
        if n == 0 {
            return Ok(self.false_lit());
        }
        // Flip sign bit and compare unsigned.
        let mut fa = a.to_vec();
        let mut fb = b.to_vec();
        fa[n - 1] = -fa[n - 1];
        fb[n - 1] = -fb[n - 1];
        self.mk_bv_ult(&fa, &fb)
    }

    fn mk_bv_sle(&mut self, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        let gt = self.mk_bv_slt(b, a)?;
        Ok(-gt)
    }

    fn mk_bv_ite(&mut self, c: i32, t: &[i32], e: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        t.iter().zip(e.iter()).map(|(&ti, &ei)| self.mk_ite(c, ti, ei)).collect()
    }

    fn mk_bv_shl(&mut self, a: &[i32], sh: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        let mut cur = a.to_vec();
        let f = self.false_lit();
        // Barrel shifter over log2(w) stages, plus clamp to 0 if sh >= w.
        let log_w = (usize::BITS - (w.saturating_sub(1)).leading_zeros()) as usize;
        for stage in 0..log_w.min(sh.len()) {
            let amt = 1usize << stage;
            let bit = sh[stage];
            let mut next = Vec::with_capacity(w);
            for i in 0..w {
                let shifted = if i >= amt { cur[i - amt] } else { f };
                next.push(self.mk_ite(bit, shifted, cur[i])?);
            }
            cur = next;
        }
        // If sh >= w, result is 0.
        let w_const = self.mk_bv_const(sh.len() as u16, w as u128);
        let in_range = self.mk_bv_ult(sh, &w_const)?;
        let zeros = vec![f; w];
        self.mk_bv_ite(in_range, &cur, &zeros)
    }

    fn mk_bv_shr(
        &mut self,
        a: &[i32],
        sh: &[i32],
        arith: bool,
    ) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        let fill = if arith && w > 0 { a[w - 1] } else { self.false_lit() };
        let mut cur = a.to_vec();
        let log_w = (usize::BITS - (w.saturating_sub(1)).leading_zeros()) as usize;
        for stage in 0..log_w.min(sh.len()) {
            let amt = 1usize << stage;
            let bit = sh[stage];
            let mut next = Vec::with_capacity(w);
            for i in 0..w {
                let shifted = if i + amt < w { cur[i + amt] } else { fill };
                next.push(self.mk_ite(bit, shifted, cur[i])?);
            }
            cur = next;
        }
        let w_const = self.mk_bv_const(sh.len() as u16, w as u128);
        let in_range = self.mk_bv_ult(sh, &w_const)?;
        let fills = vec![fill; w];
        self.mk_bv_ite(in_range, &cur, &fills)
    }

    fn mk_bv_mul(&mut self, a: &[i32], b: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        if w > 32 {
            return Err(BitBlastError::BudgetExceeded(format!(
                "bit-blasting {w}-bit multiplication exceeds SAT width limit (32)"
            )));
        }
        let f = self.false_lit();
        let mut acc = vec![f; w];
        for i in 0..w {
            let mut partial = vec![f; w];
            for j in 0..(w - i) {
                partial[i + j] = self.mk_and(a[j], b[i])?;
            }
            acc = self.mk_bv_add(&acc, &partial)?;
        }
        Ok(acc)
    }

    fn mk_bv_ctpop(&mut self, a: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        let f = self.false_lit();
        if w == 0 {
            return Ok(Vec::new());
        }
        // Balanced binary adder tree: O(w) adders total with exact minimal bit-width
        // at each level, and constant `false` in all upper bits above ceil(log2(w + 1)).
        let mut level: Vec<Vec<i32>> = a.iter().map(|&bit| vec![bit]).collect();
        while level.len() > 1 {
            let mut next = Vec::with_capacity((level.len() + 1) / 2);
            let mut i = 0;
            while i + 1 < level.len() {
                let mut x = level[i].clone();
                let mut y = level[i + 1].clone();
                let target = x.len().max(y.len()) + 1;
                x.resize(target, f);
                y.resize(target, f);
                next.push(self.mk_bv_add(&x, &y)?);
                i += 2;
            }
            if i < level.len() {
                next.push(level[i].clone());
            }
            level = next;
        }
        let mut sum = level.into_iter().next().unwrap_or_default();
        sum.truncate(w);
        sum.resize(w, f);
        Ok(sum)
    }

    fn mk_bv_ctlz(&mut self, a: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        let mut res = self.mk_bv_const(w as u16, w as u128);
        // Walk LSB -> MSB so the highest set bit overwrites earlier matches.
        for i in 0..w {
            let count = self.mk_bv_const(w as u16, (w - 1 - i) as u128);
            res = self.mk_bv_ite(a[i], &count, &res)?;
        }
        Ok(res)
    }

    fn mk_bv_cttz(&mut self, a: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        let mut res = self.mk_bv_const(w as u16, w as u128);
        // Walk MSB -> LSB so the lowest set bit overwrites earlier matches.
        for i in (0..w).rev() {
            let count = self.mk_bv_const(w as u16, i as u128);
            res = self.mk_bv_ite(a[i], &count, &res)?;
        }
        Ok(res)
    }

    fn mk_bv_fshl(&mut self, a: &[i32], b: &[i32], s: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        // w is always a power of 2 in LLVM scalar/vector types here (8, 16, 32, 64, 128).
        if !w.is_power_of_two() {
            return Err(BitBlastError::UnsupportedOp(format!(
                "non-power-of-two fshl width {w}"
            )));
        }
        let log_w = w.trailing_zeros() as usize;
        // Concatenate [b (low w bits), a (high w bits)], barrel shift left by s mod w, take high w bits.
        let mut wide = Vec::with_capacity(2 * w);
        wide.extend_from_slice(b);
        wide.extend_from_slice(a);
        let f = self.false_lit();
        for stage in 0..log_w.min(s.len()) {
            let amt = 1usize << stage;
            let bit = s[stage];
            let mut next = Vec::with_capacity(2 * w);
            for i in 0..(2 * w) {
                let shifted = if i >= amt { wide[i - amt] } else { f };
                next.push(self.mk_ite(bit, shifted, wide[i])?);
            }
            wide = next;
        }
        Ok(wide[w..2 * w].to_vec())
    }

    fn mk_bv_fshr(&mut self, a: &[i32], b: &[i32], s: &[i32]) -> Result<Vec<i32>, BitBlastError> {
        let w = a.len();
        if !w.is_power_of_two() {
            return Err(BitBlastError::UnsupportedOp(format!(
                "non-power-of-two fshr width {w}"
            )));
        }
        let log_w = w.trailing_zeros() as usize;
        let mut wide = Vec::with_capacity(2 * w);
        wide.extend_from_slice(b);
        wide.extend_from_slice(a);
        let f = self.false_lit();
        for stage in 0..log_w.min(s.len()) {
            let amt = 1usize << stage;
            let bit = s[stage];
            let mut next = Vec::with_capacity(2 * w);
            for i in 0..(2 * w) {
                let shifted = if i + amt < 2 * w { wide[i + amt] } else { f };
                next.push(self.mk_ite(bit, shifted, wide[i])?);
            }
            wide = next;
        }
        Ok(wide[0..w].to_vec())
    }
}

#[derive(Clone)]
enum BbVal {
    Bool(i32),
    Bv(Vec<i32>),
}

impl BbVal {
    fn as_bool(&self) -> i32 {
        match *self {
            BbVal::Bool(l) => l,
            _ => panic!("expected Bool"),
        }
    }

    fn as_bv(&self) -> &[i32] {
        match self {
            BbVal::Bv(v) => v,
            _ => panic!("expected Bv"),
        }
    }
}

/// Deterministically bit-blast `!obligation.goal` into a `CnfFormula`.
pub fn bitblast_obligation(
    obligation: &Obligation,
    max_clauses: usize,
) -> Result<CnfFormula, BitBlastError> {
    if obligation.theories().fp_arith {
        return Err(BitBlastError::UnsupportedOp(
            "floating-point arithmetic requires an SMT/FP backend".to_string(),
        ));
    }
    let mut ts = Tseitin::new(max_clauses);
    let mut memo: HashMap<NodeId, BbVal> = HashMap::new();
    let mut param_bits: Vec<(usize, SemTy, Vec<i32>)> = Vec::new();
    let mut param_vars: HashMap<usize, Vec<i32>> = HashMap::new();

    // Allocate parameter variables deterministically in parameter-index order.
    for p in &obligation.params {
        let bits = match p.ty {
            SemTy::Bool => vec![ts.fresh()],
            SemTy::Bv(w) => (0..w).map(|_| ts.fresh()).collect(),
            SemTy::Fp(f) => (0..f.bit_width()).map(|_| ts.fresh()).collect(),
        };
        param_vars.insert(p.index, bits.clone());
        param_bits.push((p.index, p.ty, bits));
    }

    fn mk_fp_is_nan(ts: &mut Tseitin, fmt: FpFmt, bits: &[i32]) -> Result<i32, BitBlastError> {
        let (exp_lo, exp_hi, sig_hi) = match fmt {
            FpFmt::F32 => (23usize, 31usize, 23usize),
            FpFmt::F64 => (52usize, 63usize, 52usize),
        };
        let mut exp_all1 = ts.true_lit;
        for &b in &bits[exp_lo..exp_hi] {
            exp_all1 = ts.mk_and(exp_all1, b)?;
        }
        let mut sig_nz = ts.false_lit();
        for &b in &bits[0..sig_hi] {
            sig_nz = ts.mk_or(sig_nz, b)?;
        }
        ts.mk_and(exp_all1, sig_nz)
    }

    fn mk_fp_is_finite(ts: &mut Tseitin, fmt: FpFmt, bits: &[i32]) -> Result<i32, BitBlastError> {
        let (exp_lo, exp_hi) = match fmt {
            FpFmt::F32 => (23usize, 31usize),
            FpFmt::F64 => (52usize, 63usize),
        };
        let mut exp_all1 = ts.true_lit;
        for &b in &bits[exp_lo..exp_hi] {
            exp_all1 = ts.mk_and(exp_all1, b)?;
        }
        Ok(-exp_all1)
    }

    fn mk_fp_is_zero(ts: &mut Tseitin, bits: &[i32]) -> Result<i32, BitBlastError> {
        let mut any = ts.false_lit();
        for &b in &bits[0..bits.len() - 1] {
            any = ts.mk_or(any, b)?;
        }
        Ok(-any)
    }

    fn mk_fp_olt(ts: &mut Tseitin, fmt: FpFmt, a: &[i32], b: &[i32]) -> Result<i32, BitBlastError> {
        let w = a.len();
        let nan_a = mk_fp_is_nan(ts, fmt, a)?;
        let nan_b = mk_fp_is_nan(ts, fmt, b)?;
        let uno = ts.mk_or(nan_a, nan_b)?;
        let ord = -uno;
        let za = mk_fp_is_zero(ts, a)?;
        let zb = mk_fp_is_zero(ts, b)?;
        let both_zero = ts.mk_and(za, zb)?;
        let sa = a[w - 1];
        let sb = b[w - 1];
        let mag_a = &a[0..w - 1];
        let mag_b = &b[0..w - 1];
        let mag_a_lt_b = ts.mk_bv_ult(mag_a, mag_b)?;
        let mag_b_lt_a = ts.mk_bv_ult(mag_b, mag_a)?;
        // If sa=1 (neg): lt iff (sb=0 -> true; sb=1 -> mag_b < mag_a)
        let neg_a_case = ts.mk_ite(sb, mag_b_lt_a, ts.true_lit)?;
        // If sa=0 (pos): lt iff (sb=0 -> mag_a < mag_b; sb=1 -> false)
        let pos_a_case = ts.mk_ite(sb, ts.false_lit(), mag_a_lt_b)?;
        let raw_lt = ts.mk_ite(sa, neg_a_case, pos_a_case)?;
        let not_both_zero = -both_zero;
        let nz_lt = ts.mk_and(not_both_zero, raw_lt)?;
        ts.mk_and(ord, nz_lt)
    }

    fn lower(
        g: &SemGraph,
        id: NodeId,
        ts: &mut Tseitin,
        param_vars: &HashMap<usize, Vec<i32>>,
        memo: &mut HashMap<NodeId, BbVal>,
    ) -> Result<BbVal, BitBlastError> {
        if let Some(v) = memo.get(&id) {
            return Ok(v.clone());
        }
        let res = match g.op(id) {
            SemOp::BoolConst(b) => BbVal::Bool(if *b { ts.true_lit } else { ts.false_lit() }),
            SemOp::BvConst { width, bits } => BbVal::Bv(ts.mk_bv_const(*width, *bits)),
            SemOp::FpConst { fmt, bits } => BbVal::Bv(ts.mk_bv_const(fmt.bit_width(), *bits as u128)),
            SemOp::Param { index, ty, .. } => {
                let bits = param_vars[index].clone();
                match ty {
                    SemTy::Bool => BbVal::Bool(bits[0]),
                    SemTy::Bv(_) | SemTy::Fp(_) => BbVal::Bv(bits),
                }
            }
            SemOp::Not(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(-va)
            }
            SemOp::And(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                let vb = lower(g, *b, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(ts.mk_and(va, vb)?)
            }
            SemOp::Or(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                let vb = lower(g, *b, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(ts.mk_or(va, vb)?)
            }
            SemOp::Xor(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                let vb = lower(g, *b, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(ts.mk_xor(va, vb)?)
            }
            SemOp::Iff(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                let vb = lower(g, *b, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(ts.mk_iff(va, vb)?)
            }
            SemOp::Implies(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?.as_bool();
                let vb = lower(g, *b, ts, param_vars, memo)?.as_bool();
                BbVal::Bool(ts.mk_or(-va, vb)?)
            }
            SemOp::Ite(c, t, e) => {
                let vc = lower(g, *c, ts, param_vars, memo)?.as_bool();
                let vt = lower(g, *t, ts, param_vars, memo)?;
                let ve = lower(g, *e, ts, param_vars, memo)?;
                match (vt, ve) {
                    (BbVal::Bool(lt), BbVal::Bool(le)) => BbVal::Bool(ts.mk_ite(vc, lt, le)?),
                    (BbVal::Bv(bt), BbVal::Bv(be)) => BbVal::Bv(ts.mk_bv_ite(vc, &bt, &be)?),
                    _ => unreachable!(),
                }
            }
            SemOp::BvNot(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bv(va.as_bv().iter().map(|&l| -l).collect())
            }
            SemOp::BvNeg(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let zeros = ts.mk_bv_const(va.as_bv().len() as u16, 0);
                BbVal::Bv(ts.mk_bv_sub(&zeros, va.as_bv())?)
            }
            SemOp::BvExtract { x, hi, lo } => {
                let vx = lower(g, *x, ts, param_vars, memo)?;
                BbVal::Bv(vx.as_bv()[*lo as usize..=*hi as usize].to_vec())
            }
            SemOp::BvConcat(hi, lo) => {
                let vhi = lower(g, *hi, ts, param_vars, memo)?;
                let vlo = lower(g, *lo, ts, param_vars, memo)?;
                let mut out = vlo.as_bv().to_vec();
                out.extend_from_slice(vhi.as_bv());
                BbVal::Bv(out)
            }
            SemOp::BvZExt { x, to } => {
                let vx = lower(g, *x, ts, param_vars, memo)?;
                let mut out = vx.as_bv().to_vec();
                while out.len() < *to as usize {
                    out.push(ts.false_lit());
                }
                BbVal::Bv(out)
            }
            SemOp::BvSExt { x, to } => {
                let vx = lower(g, *x, ts, param_vars, memo)?;
                let mut out = vx.as_bv().to_vec();
                let sign = *out.last().unwrap();
                while out.len() < *to as usize {
                    out.push(sign);
                }
                BbVal::Bv(out)
            }
            SemOp::BvBitReverse(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let mut out = va.as_bv().to_vec();
                out.reverse();
                BbVal::Bv(out)
            }
            SemOp::BvBSwap(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let bits = va.as_bv();
                let bytes = bits.len() / 8;
                let mut out = Vec::with_capacity(bits.len());
                for b_idx in (0..bytes).rev() {
                    out.extend_from_slice(&bits[b_idx * 8..(b_idx + 1) * 8]);
                }
                BbVal::Bv(out)
            }
            SemOp::BvCtPop(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_ctpop(va.as_bv())?)
            }
            SemOp::BvCtlz(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_ctlz(va.as_bv())?)
            }
            SemOp::BvCttz(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_cttz(va.as_bv())?)
            }
            SemOp::BvAdd(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_add(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvSub(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_sub(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvMul(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_mul(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvAnd(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let bits = va
                    .as_bv()
                    .iter()
                    .zip(vb.as_bv().iter())
                    .map(|(&x, &y)| ts.mk_and(x, y))
                    .collect::<Result<Vec<_>, _>>()?;
                BbVal::Bv(bits)
            }
            SemOp::BvOr(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let bits = va
                    .as_bv()
                    .iter()
                    .zip(vb.as_bv().iter())
                    .map(|(&x, &y)| ts.mk_or(x, y))
                    .collect::<Result<Vec<_>, _>>()?;
                BbVal::Bv(bits)
            }
            SemOp::BvXor(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let bits = va
                    .as_bv()
                    .iter()
                    .zip(vb.as_bv().iter())
                    .map(|(&x, &y)| ts.mk_xor(x, y))
                    .collect::<Result<Vec<_>, _>>()?;
                BbVal::Bv(bits)
            }
            SemOp::BvShl(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_shl(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvLShr(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_shr(va.as_bv(), vb.as_bv(), false)?)
            }
            SemOp::BvAShr(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_shr(va.as_bv(), vb.as_bv(), true)?)
            }
            SemOp::BvFshl(a, b, s) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let vs = lower(g, *s, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_fshl(va.as_bv(), vb.as_bv(), vs.as_bv())?)
            }
            SemOp::BvFshr(a, b, s) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let vs = lower(g, *s, ts, param_vars, memo)?;
                BbVal::Bv(ts.mk_bv_fshr(va.as_bv(), vb.as_bv(), vs.as_bv())?)
            }
            SemOp::BvEq(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bool(ts.mk_bv_eq(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvULt(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bool(ts.mk_bv_ult(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvULe(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bool(ts.mk_bv_ule(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvSLt(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bool(ts.mk_bv_slt(va.as_bv(), vb.as_bv())?)
            }
            SemOp::BvSLe(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                BbVal::Bool(ts.mk_bv_sle(va.as_bv(), vb.as_bv())?)
            }
            SemOp::FpToBvBits(a) | SemOp::BvBitsToFp(_, a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bv(va.as_bv().to_vec())
            }
            SemOp::FpNeg(a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let mut out = va.as_bv().to_vec();
                let top = out.len() - 1;
                out[top] = -out[top];
                BbVal::Bv(out)
            }
            SemOp::FpUnary(FpUnaryOp::Abs, a) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let mut out = va.as_bv().to_vec();
                let top = out.len() - 1;
                out[top] = ts.false_lit();
                BbVal::Bv(out)
            }
            SemOp::FpCopySign(a, b) => {
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let mut out = va.as_bv().to_vec();
                let top = out.len() - 1;
                out[top] = vb.as_bv()[top];
                BbVal::Bv(out)
            }
            SemOp::FpIsNaN(a) => {
                let fmt = g.fp_fmt(*a);
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bool(mk_fp_is_nan(ts, fmt, va.as_bv())?)
            }
            SemOp::FpIsFinite(a) => {
                let fmt = g.fp_fmt(*a);
                let va = lower(g, *a, ts, param_vars, memo)?;
                BbVal::Bool(mk_fp_is_finite(ts, fmt, va.as_bv())?)
            }
            SemOp::FpCmp(pred, a, b) => {
                let fmt = g.fp_fmt(*a);
                let va = lower(g, *a, ts, param_vars, memo)?;
                let vb = lower(g, *b, ts, param_vars, memo)?;
                let ba = va.as_bv();
                let bb = vb.as_bv();
                let nan_a = mk_fp_is_nan(ts, fmt, ba)?;
                let nan_b = mk_fp_is_nan(ts, fmt, bb)?;
                let uno = ts.mk_or(nan_a, nan_b)?;
                let ord = -uno;
                let res_lit = match pred {
                    FpPred::False => ts.false_lit(),
                    FpPred::True => ts.true_lit,
                    FpPred::Ord => ord,
                    FpPred::Uno => uno,
                    FpPred::Oeq | FpPred::One | FpPred::Ueq | FpPred::Une => {
                        let za = mk_fp_is_zero(ts, ba)?;
                        let zb = mk_fp_is_zero(ts, bb)?;
                        let both_zero = ts.mk_and(za, zb)?;
                        let bits_eq = ts.mk_bv_eq(ba, bb)?;
                        let val_eq = ts.mk_or(both_zero, bits_eq)?;
                        let oeq = ts.mk_and(ord, val_eq)?;
                        match pred {
                            FpPred::Oeq => oeq,
                            FpPred::One => ts.mk_and(ord, -val_eq)?,
                            FpPred::Ueq => ts.mk_or(uno, val_eq)?,
                            FpPred::Une => ts.mk_or(uno, -val_eq)?,
                            _ => unreachable!(),
                        }
                    }
                    FpPred::Olt => mk_fp_olt(ts, fmt, ba, bb)?,
                    FpPred::Ogt => mk_fp_olt(ts, fmt, bb, ba)?,
                    FpPred::Ole | FpPred::Oge => {
                        let lt = if matches!(pred, FpPred::Ole) {
                            mk_fp_olt(ts, fmt, ba, bb)?
                        } else {
                            mk_fp_olt(ts, fmt, bb, ba)?
                        };
                        let za = mk_fp_is_zero(ts, ba)?;
                        let zb = mk_fp_is_zero(ts, bb)?;
                        let both_zero = ts.mk_and(za, zb)?;
                        let bits_eq = ts.mk_bv_eq(ba, bb)?;
                        let val_eq = ts.mk_or(both_zero, bits_eq)?;
                        let oeq = ts.mk_and(ord, val_eq)?;
                        ts.mk_or(lt, oeq)?
                    }
                    FpPred::Ult => {
                        let olt = mk_fp_olt(ts, fmt, ba, bb)?;
                        ts.mk_or(uno, olt)?
                    }
                    FpPred::Ugt => {
                        let ogt = mk_fp_olt(ts, fmt, bb, ba)?;
                        ts.mk_or(uno, ogt)?
                    }
                    FpPred::Ule => {
                        let ogt = mk_fp_olt(ts, fmt, bb, ba)?;
                        -ogt
                    }
                    FpPred::Uge => {
                        let olt = mk_fp_olt(ts, fmt, ba, bb)?;
                        -olt
                    }
                };
                BbVal::Bool(res_lit)
            }
            other => {
                return Err(BitBlastError::UnsupportedOp(format!(
                    "operation {:?} is not supported by pure bit-blaster (route to SMT)",
                    other
                )));
            }
        };
        memo.insert(id, res.clone());
        Ok(res)
    }

    let goal_lit = lower(&obligation.graph, obligation.goal, &mut ts, &param_vars, &mut memo)?
        .as_bool();
    // Assert `!goal` so UNSAT proves `goal` is valid and SAT yields a counterexample.
    ts.add_clause(vec![-goal_lit])?;

    Ok(CnfFormula {
        num_vars: (ts.next_var - 1) as usize,
        clauses: ts.clauses,
        param_bits,
    })
}

fn reconstruct_counterexample(
    obligation: &Obligation,
    cnf: &CnfFormula,
    model: &[i8],
) -> Counterexample {
    let mut vals = Vec::with_capacity(obligation.params.len());
    for (idx, ty, bits) in &cnf.param_bits {
        let cv = match *ty {
            SemTy::Bool => ConcreteVal::Bool(model[bits[0] as usize] > 0),
            SemTy::Bv(w) => {
                let mut v = 0u128;
                for (bit_i, &var) in bits.iter().enumerate() {
                    if model[var as usize] > 0 {
                        v |= 1u128 << bit_i;
                    }
                }
                ConcreteVal::Bv { width: w, bits: v }
            }
            SemTy::Fp(fmt) => {
                let mut v = 0u64;
                for (bit_i, &var) in bits.iter().enumerate() {
                    if model[var as usize] > 0 {
                        v |= 1u64 << bit_i;
                    }
                }
                ConcreteVal::Fp { fmt, bits: v }
            }
        };
        vals.push((*idx, cv));
    }
    vals.sort_by_key(|(i, _)| *i);
    let args: Vec<ConcreteVal> = vals.into_iter().map(|(_, v)| v).collect();
    // Independently validate the counterexample against the shared semantic evaluator!
    let eval_goal = eval_node(&obligation.graph, obligation.goal, &args).as_bool();
    let validated = !eval_goal;
    let inputs = obligation
        .params
        .iter()
        .zip(args.iter())
        .map(|(p, &v)| (p.name.clone(), v.format_with_sign(p.signed)))
        .collect();
    Counterexample {
        inputs,
        validated,
        summary: format!(
            "goal `{}` falsified (evaluator confirmed: {})",
            obligation.kind, validated
        ),
    }
}

