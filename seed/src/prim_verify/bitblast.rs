/// Drop-in replacement for `CdclLratProver` that shells out to an external
/// LRAT-producing SAT solver (such as `cadical --lrat -q <cnf> <lrat>`).
#[derive(Clone, Debug)]
pub struct ExternalSatProver {
    pub name: String,
    pub binary: String,
    pub max_clauses: usize,
}

impl ExternalSatProver {
    pub fn cadical(binary: impl Into<String>) -> Self {
        Self {
            name: "external-cadical-lrat".to_string(),
            binary: binary.into(),
            max_clauses: DEFAULT_MAX_CLAUSES,
        }
    }
}

impl Prover for ExternalSatProver {
    fn id(&self) -> &str {
        &self.name
    }

    fn supported_theories(&self) -> TheorySet {
        TheorySet::bv_all()
    }

    fn prove(&self, obligation: &Obligation) -> ProverOutcome {
        let cnf = match bitblast_obligation(obligation, self.max_clauses) {
            Ok(c) => c,
            Err(BitBlastError::UnsupportedOp(m) | BitBlastError::BudgetExceeded(m)) => {
                return ProverOutcome::Unknown(m);
            }
        };
        let dir = match tempfile::tempdir() {
            Ok(d) => d,
            Err(e) => return ProverOutcome::Unknown(format!("tempdir failed: {e}")),
        };
        let cnf_path = dir.path().join("goal.cnf");
        let lrat_path = dir.path().join("proof.lrat");

        // Write DIMACS CNF.
        {
            let mut f = match std::fs::File::create(&cnf_path) {
                Ok(f) => f,
                Err(e) => return ProverOutcome::Unknown(format!("write cnf failed: {e}")),
            };
            if writeln!(f, "p cnf {} {}", cnf.num_vars, cnf.clauses.len()).is_err() {
                return ProverOutcome::Unknown("failed writing DIMACS header".to_string());
            }
            for cl in &cnf.clauses {
                for &l in cl {
                    let _ = write!(f, "{l} ");
                }
                let _ = writeln!(f, "0");
            }
        }

        let out = match Command::new(&self.binary)
            .arg("--lrat")
            .arg("-q")
            .arg(&cnf_path)
            .arg(&lrat_path)
            .stdin(Stdio::null())
            .output()
        {
            Ok(o) => o,
            Err(e) => {
                return ProverOutcome::Unknown(format!(
                    "failed to spawn `{}`: {e}",
                    self.binary
                ));
            }
        };

        // Standard SAT competition exit codes: 20 = UNSAT, 10 = SAT.
        match out.status.code() {
            Some(20) => match std::fs::read_to_string(&lrat_path) {
                Ok(lrat) => ProverOutcome::Proved(Evidence {
                    format: LRAT_FORMAT_ID.to_string(),
                    prover_id: self.id().to_string(),
                    payload: lrat,
                }),
                Err(e) => ProverOutcome::Unknown(format!("failed reading LRAT output: {e}")),
            },
            Some(10) => {
                let stdout = String::from_utf8_lossy(&out.stdout);
                let mut model = vec![-1i8; cnf.num_vars + 1];
                for line in stdout.lines() {
                    if let Some(rest) = line.strip_prefix("v ") {
                        for tok in rest.split_whitespace() {
                            if let Ok(lit) = tok.parse::<i32>() {
                                let v = lit.unsigned_abs() as usize;
                                if v > 0 && v <= cnf.num_vars {
                                    model[v] = if lit > 0 { 1 } else { -1 };
                                }
                            }
                        }
                    }
                }
                ProverOutcome::Disproved(reconstruct_counterexample(obligation, &cnf, &model))
            }
            other => ProverOutcome::Unknown(format!(
                "`{}` exited with {:?}: {}",
                self.binary,
                other,
                String::from_utf8_lossy(&out.stderr).trim()
            )),
        }
    }
}
