//! Deterministic Tseitin bit-blaster, built-in CDCL SAT solver with LRAT proof
//! emission, external SAT solver adapter, and independent LRAT proof checkers.
//!
//! Architecture:
//! - Both prover and checker deterministically bit-blast the same `Obligation`
//!   into DIMACS CNF, preventing a malicious prover from swapping the formula.
//! - The prover is UNTRUSTED search (`CdclLratProver` or `ExternalSatProver`)
//!   that emits an `lrat/v1` certificate (or a SAT model → `Counterexample`).
//! - `CompiledLratChecker` and `KernelLratChecker` are tiny, standalone RUP
//!   verifiers sharing zero solver state.

