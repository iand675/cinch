/// Pure-Rust CDCL SAT solver that emits standard LRAT refutation certificates.
/// Can be replaced at any time with CaDiCaL/Kissat via `ExternalSatProver`.
#[derive(Clone, Debug)]
pub struct CdclLratProver {
    pub max_clauses: usize,
    pub max_conflicts: usize,
}

impl Default for CdclLratProver {
    fn default() -> Self {
        Self {
            max_clauses: DEFAULT_MAX_CLAUSES,
            max_conflicts: DEFAULT_MAX_CONFLICTS,
        }
    }
}

impl Prover for CdclLratProver {
    fn id(&self) -> &str {
        "cdcl-lrat-builtin@1"
    }

    fn supported_theories(&self) -> TheorySet {
        TheorySet::bv_all()
    }

    fn prove(&self, obligation: &Obligation) -> ProverOutcome {
        let cnf = match bitblast_obligation(obligation, self.max_clauses) {
            Ok(c) => c,
            Err(BitBlastError::UnsupportedOp(msg) | BitBlastError::BudgetExceeded(msg)) => {
                return ProverOutcome::Unknown(msg);
            }
        };
        match solve_cdcl_lrat(&cnf, self.max_conflicts) {
            SatOutcome::Unsat(lrat_text) => ProverOutcome::Proved(Evidence {
                format: LRAT_FORMAT_ID.to_string(),
                prover_id: self.id().to_string(),
                payload: lrat_text,
            }),
            SatOutcome::Sat(model) => {
                ProverOutcome::Disproved(reconstruct_counterexample(obligation, &cnf, &model))
            }
            SatOutcome::Unknown(reason) => ProverOutcome::Unknown(reason),
        }
    }
}

enum SatOutcome {
    Sat(Vec<i8>),
    Unsat(String),
    Unknown(String),
}

struct CdclSolver {
    num_vars: usize,
    /// Clauses indexed by 0-based slot; each clause has a 1-based LRAT `id`.
    clauses: Vec<Vec<i32>>,
    clause_ids: Vec<usize>,
    /// Map from 1-based LRAT clause ID -> 0-based slot in `clauses`.
    id_to_slot: HashMap<usize, usize>,
    /// Two-watched literals: `watches[lit_idx]` lists clause slots watching `lit`.
    watches: Vec<Vec<usize>>,
    /// Assignment per 1-based variable: 0 = unassigned, 1 = true, -1 = false.
    assign: Vec<i8>,
    level: Vec<usize>,
    /// 1-based LRAT clause ID that propagated `var`, or `None` if decision.
    reason: Vec<Option<usize>>,
    /// Position of `var` in `trail` (for ordering level-0 antecedents).
    trail_pos: Vec<usize>,
    trail: Vec<i32>,
    trail_lim: Vec<usize>,
    qhead: usize,
    activity: Vec<f64>,
    var_inc: f64,
    next_id: usize,
    lrat_lines: Vec<String>,
}

impl CdclSolver {
    fn lit_idx(lit: i32) -> usize {
        let v = lit.unsigned_abs() as usize;
        if lit > 0 { v * 2 } else { v * 2 + 1 }
    }

    fn new(cnf: &CnfFormula) -> Self {
        let n = cnf.num_vars;
        Self {
            num_vars: n,
            clauses: Vec::with_capacity(cnf.clauses.len() + 256),
            clause_ids: Vec::with_capacity(cnf.clauses.len() + 256),
            id_to_slot: HashMap::with_capacity(cnf.clauses.len() + 256),
            watches: vec![Vec::new(); (n + 1) * 2],
            assign: vec![0; n + 1],
            level: vec![0; n + 1],
            reason: vec![None; n + 1],
            trail_pos: vec![0; n + 1],
            trail: Vec::with_capacity(n),
            trail_lim: Vec::new(),
            qhead: 0,
            activity: vec![0.0; n + 1],
            var_inc: 1.0,
            next_id: 1,
            lrat_lines: Vec::new(),
        }
    }

    fn val_lit_in(assign: &[i8], lit: i32) -> i8 {
        let a = assign[lit.unsigned_abs() as usize];
        if lit > 0 { a } else { -a }
    }

    fn val_lit(&self, lit: i32) -> i8 {
        Self::val_lit_in(&self.assign, lit)
    }

    fn decision_level(&self) -> usize {
        self.trail_lim.len()
    }

    fn enqueue(&mut self, lit: i32, reason_id: Option<usize>) {
        let v = lit.unsigned_abs() as usize;
        self.assign[v] = if lit > 0 { 1 } else { -1 };
        self.level[v] = self.decision_level();
        self.reason[v] = reason_id;
        self.trail_pos[v] = self.trail.len();
        self.trail.push(lit);
    }

    fn add_clause_internal(&mut self, lits: Vec<i32>) -> usize {
        let id = self.next_id;
        self.next_id += 1;
        let slot = self.clauses.len();
        if lits.len() >= 2 {
            self.watches[Self::lit_idx(lits[0])].push(slot);
            self.watches[Self::lit_idx(lits[1])].push(slot);
        }
        self.clauses.push(lits);
        self.clause_ids.push(id);
        self.id_to_slot.insert(id, slot);
        id
    }

    /// Propagate queued literals; returns `Some(conflict_clause_id)` on conflict.
    fn propagate(&mut self) -> Option<usize> {
        while self.qhead < self.trail.len() {
            let p = self.trail[self.qhead];
            self.qhead += 1;
            let false_lit = -p;
            let widx = Self::lit_idx(false_lit);
            let mut ws = std::mem::take(&mut self.watches[widx]);
            let mut i = 0;
            let mut conflict: Option<usize> = None;

            while i < ws.len() {
                let slot = ws[i];
                let cl = &mut self.clauses[slot];
                // Ensure `false_lit` is at `cl[1]`.
                if cl[0] == false_lit {
                    cl.swap(0, 1);
                }
                let first = cl[0];
                if Self::val_lit_in(&self.assign, first) == 1 {
                    i += 1;
                    continue;
                }
                // Look for a new watch among cl[2..].
                let mut found = false;
                for k in 2..cl.len() {
                    if Self::val_lit_in(&self.assign, cl[k]) != -1 {
                        cl.swap(1, k);
                        let new_watch = cl[1];
                        self.watches[Self::lit_idx(new_watch)].push(slot);
                        ws.swap_remove(i);
                        found = true;
                        break;
                    }
                }
                if found {
                    continue;
                }
                // No replacement watch: clause is either unit (`first`) or conflicting!
                let cid = self.clause_ids[slot];
                if self.val_lit(first) == -1 {
                    conflict = Some(cid);
                    break;
                } else {
                    self.enqueue(first, Some(cid));
                    i += 1;
                }
            }
            // Restore remaining watches (including anything newly pushed onto `self.watches[widx]`).
            if self.watches[widx].is_empty() {
                self.watches[widx] = ws;
            } else {
                ws.extend(std::mem::take(&mut self.watches[widx]));
                self.watches[widx] = ws;
            }
            if conflict.is_some() {
                self.qhead = self.trail.len();
                return conflict;
            }
        }
        None
    }

    /// Collect all level-0 reason clause IDs needed to derive variables in `seeds`,
    /// ordered by ascending `trail_pos` so RUP propagation succeeds in one pass.
    fn collect_level0_hints(&self, seeds: &[usize]) -> Vec<usize> {
        let mut visited: HashSet<usize> = HashSet::new();
        let mut stack: Vec<usize> = seeds.to_vec();
        let mut ordered: Vec<(usize, usize)> = Vec::new();
        while let Some(v) = stack.pop() {
            if !visited.insert(v) {
                continue;
            }
            if let Some(rid) = self.reason[v] {
                ordered.push((self.trail_pos[v], rid));
                let slot = self.id_to_slot[&rid];
                for &lit in &self.clauses[slot] {
                    let u = lit.unsigned_abs() as usize;
                    if u != v && self.level[u] == 0 {
                        stack.push(u);
                    }
                }
            }
        }
        ordered.sort_by_key(|&(pos, _)| pos);
        let mut out = Vec::with_capacity(ordered.len());
        let mut seen_id = HashSet::new();
        for (_, rid) in ordered {
            if seen_id.insert(rid) {
                out.push(rid);
            }
        }
        out
    }

    /// 1-UIP conflict analysis returning `(learned_clause, backtrack_level, lrat_hints)`.
    fn analyze(&mut self, conflict_id: usize) -> (Vec<i32>, usize, Vec<usize>) {
        let cur_lvl = self.decision_level();
        let mut seen = vec![false; self.num_vars + 1];
        let mut learned: Vec<i32> = Vec::new();
        let mut lvl0_vars: Vec<usize> = Vec::new();
        let mut resolved_ids: Vec<usize> = Vec::new();
        let mut counter = 0usize;

        // Placehold slot 0 for the asserting 1-UIP literal.
        learned.push(0);

        let mut cur_cid = conflict_id;
        let mut trail_idx = self.trail.len();
        let mut skip_var: usize = 0;

        loop {
            resolved_ids.push(cur_cid);
            let slot = self.id_to_slot[&cur_cid];
            let lits = self.clauses[slot].clone();
            for lit in lits {
                let v = lit.unsigned_abs() as usize;
                if v == skip_var || seen[v] {
                    continue;
                }
                seen[v] = true;
                self.bump_var(v);
                let lv = self.level[v];
                if lv == cur_lvl {
                    counter += 1;
                } else if lv > 0 {
                    learned.push(lit);
                } else {
                    lvl0_vars.push(v);
                }
            }

            // Walk backward on trail to next seen literal at current decision level.
            let next_lit = loop {
                trail_idx -= 1;
                let p = self.trail[trail_idx];
                if seen[p.unsigned_abs() as usize] {
                    break p;
                }
            };
            let v = next_lit.unsigned_abs() as usize;
            counter -= 1;
            if counter == 0 {
                learned[0] = -next_lit;
                break;
            }
            skip_var = v;
            cur_cid = self.reason[v].expect("non-UIP literal at current level must have a reason");
        }

        // Compute backtrack level and move a literal at that level to index 1 for watching.
        let mut bt_level = 0usize;
        if learned.len() > 1 {
            let mut best = 1usize;
            for i in 1..learned.len() {
                let lv = self.level[learned[i].unsigned_abs() as usize];
                if lv > bt_level {
                    bt_level = lv;
                    best = i;
                }
            }
            learned.swap(1, best);
        }

        // Build exact LRAT RUP hint list:
        // 1. Needed level-0 reason clauses in forward trail order.
        // 2. Resolved current-level clauses in reverse resolution order (forward propagation order).
        let mut hints = self.collect_level0_hints(&lvl0_vars);
        let mut seen_hint: HashSet<usize> = hints.iter().copied().collect();
        for &cid in resolved_ids.iter().rev() {
            if seen_hint.insert(cid) {
                hints.push(cid);
            }
        }

        self.var_inc *= 1.05;
        if self.var_inc > 1e100 {
            for a in &mut self.activity {
                *a *= 1e-100;
            }
            self.var_inc *= 1e-100;
        }
        (learned, bt_level, hints)
    }

    fn bump_var(&mut self, v: usize) {
        self.activity[v] += self.var_inc;
    }

    fn backtrack(&mut self, target_level: usize) {
        if self.decision_level() <= target_level {
            return;
        }
        let lim = self.trail_lim[target_level];
        while self.trail.len() > lim {
            let p = self.trail.pop().unwrap();
            let v = p.unsigned_abs() as usize;
            self.assign[v] = 0;
            self.reason[v] = None;
        }
        self.trail_lim.truncate(target_level);
        self.qhead = self.trail.len();
    }

    fn log_lrat_add(&mut self, id: usize, lits: &[i32], hints: &[usize]) {
        let mut line = format!("{id}");
        for &l in lits {
            line.push_str(&format!(" {l}"));
        }
        line.push_str(" 0");
        for &h in hints {
            line.push_str(&format!(" {h}"));
        }
        line.push_str(" 0");
        self.lrat_lines.push(line);
    }

    fn emit_level0_empty_clause(&mut self, conflict_id: usize) -> String {
        let slot = self.id_to_slot[&conflict_id];
        let seeds: Vec<usize> = self.clauses[slot]
            .iter()
            .map(|l| l.unsigned_abs() as usize)
            .collect();
        let mut hints = self.collect_level0_hints(&seeds);
        if !hints.contains(&conflict_id) {
            hints.push(conflict_id);
        }
        let empty_id = self.next_id;
        self.next_id += 1;
        self.log_lrat_add(empty_id, &[], &hints);
        self.lrat_lines.join("\n")
    }

    fn pick_branch_var(&self) -> Option<usize> {
        let mut best: Option<(usize, f64)> = None;
        for v in 1..=self.num_vars {
            if self.assign[v] == 0 {
                let act = self.activity[v];
                if best.map_or(true, |(_, ba)| act > ba) {
                    best = Some((v, act));
                }
            }
        }
        best.map(|(v, _)| v)
    }
}

fn solve_cdcl_lrat(cnf: &CnfFormula, max_conflicts: usize) -> SatOutcome {
    let mut s = CdclSolver::new(cnf);
    let mut unit_queue: Vec<(i32, usize)> = Vec::new();
    let mut immediate_empty: Option<usize> = None;

    for cl in &cnf.clauses {
        let id = s.add_clause_internal(cl.clone());
        match cl.len() {
            0 => immediate_empty = Some(id),
            1 => unit_queue.push((cl[0], id)),
            _ => {}
        }
    }

    if let Some(eid) = immediate_empty {
        let out_id = s.next_id;
        s.log_lrat_add(out_id, &[], &[eid]);
        return SatOutcome::Unsat(s.lrat_lines.join("\n"));
    }

    // Enqueue original unit clauses (detecting direct level-0 contradiction).
    for (lit, cid) in unit_queue {
        match s.val_lit(lit) {
            1 => {}
            -1 => return SatOutcome::Unsat(s.emit_level0_empty_clause(cid)),
            0 => s.enqueue(lit, Some(cid)),
            _ => unreachable!(),
        }
    }

    let mut conflicts = 0usize;
    let mut restart_limit = 200usize;
    let mut since_restart = 0usize;

    loop {
        if let Some(conf_id) = s.propagate() {
            conflicts += 1;
            since_restart += 1;
            if s.decision_level() == 0 {
                return SatOutcome::Unsat(s.emit_level0_empty_clause(conf_id));
            }
            if conflicts > max_conflicts {
                return SatOutcome::Unknown(format!(
                    "CDCL conflict budget ({max_conflicts}) exceeded"
                ));
            }
            let (learned, bt_level, hints) = s.analyze(conf_id);
            let asserting = learned[0];
            let new_id = s.add_clause_internal(learned.clone());
            s.log_lrat_add(new_id, &learned, &hints);
            s.backtrack(bt_level);
            s.enqueue(asserting, Some(new_id));
        } else {
            if since_restart >= restart_limit {
                s.backtrack(0);
                since_restart = 0;
                restart_limit = (restart_limit * 3) / 2 + 50;
            }
            match s.pick_branch_var() {
                None => return SatOutcome::Sat(s.assign),
                Some(v) => {
                    s.trail_lim.push(s.trail.len());
                    s.enqueue(-(v as i32), None);
                }
            }
        }
    }
}

