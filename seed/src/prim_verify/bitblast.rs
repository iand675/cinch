/// Verify an `lrat/v1` refutation certificate against `cnf`.
/// This function is the entire SAT-proof trusted core (~115 lines).
///
/// Uses direct clause-ID indexing (`Vec<Option<Vec<i32>>>`) and an O(1)-reset
/// undo trail over a single reusable assignment array (Cruz-Filipe, Heule,
/// Hunt, Kaufmann, Schneider-Kamp, CADE 2017) so verification runs in
/// O(total hints) time instead of O(steps * vars).
pub fn verify_lrat(cnf: &CnfFormula, lrat_text: &str) -> Result<usize, CheckError> {
    let mut db: Vec<Option<Vec<i32>>> = Vec::with_capacity(cnf.clauses.len() + 65);
    db.push(None); // 1-based indexing
    for cl in &cnf.clauses {
        db.push(Some(cl.clone()));
    }
    let mut assign: Vec<i8> = vec![0; cnf.num_vars + 1];
    let mut undo: Vec<usize> = Vec::with_capacity(64);
    let mut steps = 0usize;
    let mut derived_empty = false;

    for (line_no, raw) in lrat_text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('c') {
            continue;
        }
        let mut toks = line.split_whitespace();
        let first = toks.next().ok_or_else(|| {
            CheckError::InvalidCertificate(format!("lrat line {}: malformed entry", line_no + 1))
        })?;
        let second = toks.next().ok_or_else(|| {
            CheckError::InvalidCertificate(format!("lrat line {}: malformed entry", line_no + 1))
        })?;
        // Deletion line: `<id> d <del_id...> 0`
        if second == "d" {
            for t in toks {
                let did: usize = t.parse().map_err(|_| {
                    CheckError::InvalidCertificate(format!("lrat line {}: bad delete id `{t}`", line_no + 1))
                })?;
                if did == 0 {
                    break;
                }
                if did < db.len() {
                    db[did] = None;
                }
            }
            continue;
        }

        // Addition line: `<new_id> <lit...> 0 <hint_id...> 0`
        let new_id: usize = first.parse().map_err(|_| {
            CheckError::InvalidCertificate(format!("lrat line {}: bad clause id", line_no + 1))
        })?;
        let mut lits = Vec::new();
        let mut cur_tok = Some(second);
        while let Some(t) = cur_tok {
            let l: i32 = t.parse().map_err(|_| {
                CheckError::InvalidCertificate(format!("lrat line {}: bad literal", line_no + 1))
            })?;
            if l == 0 {
                break;
            }
            let v = l.unsigned_abs() as usize;
            if v >= assign.len() {
                assign.resize(v + 1, 0);
            }
            lits.push(l);
            cur_tok = toks.next();
        }
        let mut hints = Vec::new();
        for t in toks {
            let h: i64 = t.parse().map_err(|_| {
                CheckError::InvalidCertificate(format!("lrat line {}: bad hint id", line_no + 1))
            })?;
            if h == 0 {
                break;
            }
            if h < 0 {
                return Err(CheckError::InvalidCertificate(format!(
                    "lrat line {}: RAT hints are not accepted in RUP-only checker",
                    line_no + 1
                )));
            }
            hints.push(h as usize);
        }

        // Check Reverse Unit Propagation (RUP): assume negation of every literal in `lits`.
        let mut conflict = false;
        for &l in &lits {
            let v = l.unsigned_abs() as usize;
            let want = if l > 0 { -1 } else { 1 };
            if assign[v] == -want {
                // Tautological clause (`l` and `-l` both present).
                conflict = true;
                break;
            }
            if assign[v] == 0 {
                assign[v] = want;
                undo.push(v);
            }
        }

        let mut step_err: Option<CheckError> = None;
        if !conflict {
            for &hid in &hints {
                let Some(hcl) = db.get(hid).and_then(|o| o.as_ref()) else {
                    step_err = Some(CheckError::InvalidCertificate(format!(
                        "lrat line {}: unknown hint clause id {hid}",
                        line_no + 1
                    )));
                    break;
                };
                let mut unassigned: Option<i32> = None;
                let mut satisfied = false;
                let mut multiple_unassigned = false;
                for &hl in hcl {
                    let v = hl.unsigned_abs() as usize;
                    let val = if v < assign.len() {
                        if hl > 0 { assign[v] } else { -assign[v] }
                    } else {
                        0
                    };
                    if val == 1 {
                        satisfied = true;
                        break;
                    } else if val == 0 {
                        if unassigned.is_some() {
                            multiple_unassigned = true;
                            break;
                        }
                        unassigned = Some(hl);
                    }
                }
                if satisfied {
                    continue;
                }
                if multiple_unassigned {
                    step_err = Some(CheckError::InvalidCertificate(format!(
                        "lrat line {}: hint clause {hid} is not unit under current assumptions",
                        line_no + 1
                    )));
                    break;
                }
                match unassigned {
                    None => {
                        conflict = true;
                        break;
                    }
                    Some(u) => {
                        let v = u.unsigned_abs() as usize;
                        if v >= assign.len() {
                            assign.resize(v + 1, 0);
                        }
                        assign[v] = if u > 0 { 1 } else { -1 };
                        undo.push(v);
                    }
                }
            }
        }

        // O(touched) undo reset.
        for v in undo.drain(..) {
            assign[v] = 0;
        }

        if let Some(err) = step_err {
            return Err(err);
        }
        if !conflict {
            return Err(CheckError::InvalidCertificate(format!(
                "lrat line {}: clause {new_id} failed RUP verification",
                line_no + 1
            )));
        }

        steps += 1;
        if lits.is_empty() {
            derived_empty = true;
            break;
        }
        if new_id >= db.len() {
            db.resize(new_id + 1, None);
        }
        db[new_id] = Some(lits);
    }

    if !derived_empty {
        return Err(CheckError::InvalidCertificate(
            "lrat certificate ended without deriving the empty clause".to_string(),
        ));
    }
    Ok(steps)
}

/// Fast compiled LRAT checker (`TrustTier::CompiledCert`, analogous to Lean's `bv_decide`).
#[derive(Clone, Debug)]
pub struct CompiledLratChecker {
    pub max_clauses: usize,
}

impl Default for CompiledLratChecker {
    fn default() -> Self {
        Self { max_clauses: DEFAULT_MAX_CLAUSES }
    }
}

impl Checker for CompiledLratChecker {
    fn id(&self) -> &str {
        "cinch-compiled-lrat@1"
    }

    fn format(&self) -> &str {
        LRAT_FORMAT_ID
    }

    fn check(&self, obligation: &Obligation, evidence: &Evidence) -> Result<TrustReceipt, CheckError> {
        let cnf = bitblast_obligation(obligation, self.max_clauses)
            .map_err(|e| CheckError::CannotReconstruct(format!("{e:?}")))?;
        let steps = verify_lrat(&cnf, &evidence.payload)?;
        Ok(TrustReceipt {
            goal_hash: obligation.goal_hash.clone(),
            semantics_id: obligation.semantics_id.clone(),
            evidence_format: LRAT_FORMAT_ID.to_string(),
            checker_id: self.id().to_string(),
            tcb: vec![
                self.id().to_string(),
                BITBLAST_VERSION_ID.to_string(),
                obligation.semantics_id.clone(),
            ],
            tier: TrustTier::CompiledCert,
            details: format!(
                "verified {steps} LRAT RUP step(s) over {} CNF vars / {} clauses",
                cnf.num_vars,
                cnf.clauses.len()
            ),
        })
    }
}

